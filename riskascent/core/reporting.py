"""Executive reporting.

Every report is generated from the live simulation data passed in by
Game.report_data(); nothing here is hard-coded sample content. Output is a
self-contained HTML document (inline CSS/SVG) suitable for preview, export
to .html, or printing to PDF.
"""

from __future__ import annotations

import html
from datetime import datetime
from typing import Any

from .kri import STATUS_CRIT, STATUS_WARN
from .org_sim import METRIC_LABELS
from .risk_engine import LIMITATIONS, heatmap_counts, prioritize
from .util import fmt_money

REPORT_KINDS = {
    "exec_dashboard": ("Executive risk dashboard", 1),
    "top_risks": ("Top-risk summary", 1),
    "heatmap": ("Risk heat maps", 1),
    "kri_trends": ("KRI trend report", 2),
    "post_incident": ("Post-incident review", 3),
    "investment_proposal": ("Treatment investment proposal", 4),
    "risk_committee": ("Risk committee report", 6),
    "board_summary": ("Board risk summary", 8),
}

CSS = """
body{font-family:'Segoe UI',Arial,sans-serif;color:#1d2433;margin:28px;font-size:13px;line-height:1.45}
h1{font-size:22px;margin:0 0 4px} h2{font-size:15px;margin:22px 0 8px;border-bottom:2px solid #1f6f8b;padding-bottom:3px}
.sub{color:#5b6475;margin-bottom:16px} table{border-collapse:collapse;width:100%;margin:6px 0}
th,td{border:1px solid #d5dae3;padding:5px 7px;text-align:left;vertical-align:top} th{background:#eef2f7}
.tile{border:1px solid #d5dae3;padding:8px 10px}
.tag{padding:1px 6px;border-radius:8px;font-size:11px;color:#fff}
.Critical,.Outside{background:#b3261e} .High,.Above,.Warning{background:#c77700} .Medium{background:#b59a00}
.Low,.Within,.Normal{background:#2e7d32} .note{color:#5b6475;font-size:11px} .hm td{width:44px;height:30px;text-align:center;font-weight:600;color:#fff}
ul{margin:4px 0 4px 18px;padding:0}
"""

BAND_COLORS = {"Low": "#2e7d32", "Medium": "#b59a00", "High": "#c77700", "Critical": "#b3261e"}


def esc(x: Any) -> str:
    return html.escape(str(x if x is not None else ""))


def _tag(text: str) -> str:
    cls = text.split()[0] if text else ""
    return f'<span class="tag {esc(cls)}">{esc(text)}</span>'


def _doc(title: str, d: dict, body: str) -> str:
    org = d["org"]
    head = (f"<h1>{esc(title)}</h1><div class='sub'>{esc(org['name'])} &middot; Month {d['period']} &middot; "
            f"Prepared by {esc(d['player'])}, {esc(d['title'])} &middot; Generated "
            f"{datetime.now():%d %b %Y %H:%M}</div>")
    foot = ("<p class='note'>Generated by Risk Ascent from simulated organisational data. Scores on the "
            "likelihood x impact matrix are ordinal rankings, not financial measures. " + esc(LIMITATIONS) + "</p>")
    return (f"<!doctype html><html><head><meta charset='utf-8'><title>{esc(title)}</title><style>{CSS}</style>"
            f"</head><body>{head}{body}{foot}</body></html>")


def _money(d: dict, v: float) -> str:
    return fmt_money(v, d["currency"])


def _tiles(d: dict) -> str:
    m = d["metrics"]
    hist = d["history"]
    prev = hist[-2][1] if len(hist) >= 2 else m
    out = []
    for k in ["revenue", "cash", "reputation", "compliance", "control_effectiveness", "resilience",
              "morale", "risk_exposure"]:
        v = m.get(k, 0)
        dv = v - prev.get(k, v)
        val = _money(d, v) if k in ("revenue", "cash") else f"{v:.0f}"
        delta = (_money(d, dv) if k in ("revenue", "cash") else f"{dv:+.1f}") if dv else "no change"
        out.append(f"<td class='tile' width='25%'>{esc(METRIC_LABELS.get(k, k))}<br>"
                   f"<span style='font-size:17px;font-weight:700'>{val}</span><br>"
                   f"<span class='note'>vs last month: {esc(delta)}</span></td>")
    # A table rather than flexbox so the in-app preview and PDF (Qt rich text) lay it out the same way.
    rows = ["<tr>" + "".join(out[i:i + 4]) + "</tr>" for i in range(0, len(out), 4)]
    return "<table class='tiles' cellpadding='8'>" + "".join(rows) + "</table>"


def _risk_table(d: dict, risks: list[dict], with_el: bool = True) -> str:
    rows = []
    for r in risks:
        band = d["matrix"].band(r["res_score"])
        rows.append(
            f"<tr><td>{esc(r['risk_id'])}</td><td><b>{esc(r['title'])}</b><br><span class='note'>"
            f"{esc(r['cause'])} &rarr; {esc(r['event'])} &rarr; {esc(r['consequence'])}</span></td>"
            f"<td>{esc(r['category'])}</td><td>{esc(r['owner'])}</td>"
            f"<td>{r['inh_l']}x{r['inh_i']}={r['inh_score']}</td><td>{r['res_l']}x{r['res_i']}={r['res_score']} {_tag(band)}</td>"
            f"<td>{_tag(r['appetite'])}</td><td>{esc(r['treatment'])}</td>"
            + (f"<td>{_money(d, r['el'])}</td>" if with_el else "") + "</tr>")
    head = ("<tr><th>ID</th><th>Risk (cause &rarr; event &rarr; consequence)</th><th>Category</th><th>Owner</th>"
            "<th>Inherent</th><th>Residual</th><th>Appetite</th><th>Treatment</th>"
            + ("<th>Indicative annual EL*</th>" if with_el else "") + "</tr>")
    note = ("<p class='note'>*Indicative expected loss uses the midpoint of the likelihood and impact ranges "
            "of each rating. It is a rough order of magnitude only; use the Financial Lab for decisions.</p>") if with_el else ""
    return f"<table>{head}{''.join(rows)}</table>{note}"


def _heatmap(d: dict, residual: bool) -> str:
    m = d["matrix"]
    grid = heatmap_counts(d["risks"], m.size, residual)
    rows = []
    for i in range(m.size, 0, -1):
        cells = []
        for l in range(1, m.size + 1):
            band = m.band(l * i)
            n = grid[i - 1][l - 1]
            cells.append(f"<td style='background:{BAND_COLORS[band]};opacity:{1 if n else 0.45}'>{n or ''}</td>")
        rows.append(f"<tr><th>{esc(m.impact_labels[i - 1])}</th>{''.join(cells)}</tr>")
    foot = "<tr><th></th>" + "".join(f"<th style='font-size:10px'>{esc(x)}</th>" for x in m.likelihood_labels) + "</tr>"
    label = "Residual" if residual else "Inherent"
    return (f"<div style='display:inline-block;margin-right:24px'><b>{label} risk</b>"
            f"<table class='hm' style='width:auto'>{''.join(rows)}{foot}</table>"
            "<span class='note'>Rows: impact. Columns: likelihood. Numbers: count of risks.</span></div>")


def _spark(values: list[float], warn: float, crit: float, w: int = 160, h: int = 34) -> str:
    if len(values) < 2:
        return "<span class='note'>Not enough history</span>"
    lo = min(values + [warn, crit])
    hi = max(values + [warn, crit])
    span = (hi - lo) or 1
    pts = " ".join(f"{i * (w - 4) / (len(values) - 1) + 2:.1f},{h - 2 - (v - lo) / span * (h - 4):.1f}"
                   for i, v in enumerate(values))

    def y(v: float) -> float:
        return h - 2 - (v - lo) / span * (h - 4)

    return (f"<svg width='{w}' height='{h}' xmlns='http://www.w3.org/2000/svg'>"
            f"<line x1='0' x2='{w}' y1='{y(warn):.1f}' y2='{y(warn):.1f}' stroke='#c77700' stroke-dasharray='3,2'/>"
            f"<line x1='0' x2='{w}' y1='{y(crit):.1f}' y2='{y(crit):.1f}' stroke='#b3261e' stroke-dasharray='3,2'/>"
            f"<polyline fill='none' stroke='#1f6f8b' stroke-width='2' points='{pts}'/></svg>")


def _kri_table(d: dict) -> str:
    rows = []
    for item in d["kris"]:
        k = item["kri"]
        vals = [v for _, v in item["history"]]
        rows.append(f"<tr><td><b>{esc(k.name)}</b><br><span class='note'>{esc(k.data_source)} &middot; "
                    f"{esc(k.frequency)} &middot; owner {esc(k.owner)}</span></td>"
                    f"<td>{k.baseline:g}</td><td><b>{k.current:g}</b> {esc(k.unit)}</td><td>{k.warning:g} / {k.critical:g}</td>"
                    f"<td>{_tag(k.status())}</td><td>{esc(k.trend())}</td><td>{_spark(vals, k.warning, k.critical)}</td>"
                    f"<td>{esc(k.escalation)}</td></tr>")
    return ("<table><tr><th>Indicator</th><th>Baseline</th><th>Current</th><th>Warn / Crit</th><th>Status</th>"
            "<th>Trend</th><th>History</th><th>Escalation</th></tr>" + "".join(rows) + "</table>")


def _insights(d: dict) -> list[str]:
    out = []
    risks = d["risks"]
    outside = [r for r in risks if r["appetite"] == "Outside tolerance" and r["status"] != "Closed"]
    if outside:
        out.append(f"{len(outside)} risk(s) are outside tolerance: "
                   + ", ".join(f"{r['risk_id']} {r['title']}" for r in outside[:4]) + ". These need a decision.")
    accepted = [r for r in outside if r["treatment"] == "Accept"]
    if accepted:
        out.append(f"{len(accepted)} risk(s) outside tolerance are marked 'Accept'. Acceptance beyond tolerance "
                   "requires explicit approval by an authorised executive; confirm this has been obtained.")
    weak = [r for r in risks if r["res_score"] >= 12 and (r["control_eff"] or 0) <= 1]
    if weak:
        out.append(f"{len(weak)} high residual risk(s) rely on weak or untested controls.")
    overdue = []
    for r in risks:
        try:
            if r["status"] not in ("Closed", "Monitoring") and r["target_date"] and int(r["target_date"]) < d["period"]:
                overdue.append(r)
        except (TypeError, ValueError):
            pass
    if overdue:
        out.append(f"{len(overdue)} treatment action(s) are past their target month.")
    worsening = [i["kri"] for i in d["kris"] if i["kri"].trend() == "Worsening"]
    if worsening:
        out.append("Worsening indicators: " + ", ".join(k.name for k in worsening[:4]) + ".")
    crit = [i["kri"] for i in d["kris"] if i["kri"].status() == STATUS_CRIT]
    if crit:
        out.append("Critical KRI breaches requiring escalation: " + ", ".join(k.name for k in crit) + ".")
    incidents = [e for e in d["events"] if e["type"] in ("incident", "scheduled", "random") and e["period"] > d["period"] - 3]
    if incidents:
        out.append(f"{len(incidents)} incident(s)/event(s) in the last three months.")
    if not out:
        out.append("No exposures outside tolerance and no critical indicators this period.")
    return out


def generate(kind: str, d: dict, options: dict | None = None) -> str:
    options = options or {}
    if kind not in REPORT_KINDS:
        raise ValueError(f"Unknown report kind {kind}")
    title = REPORT_KINDS[kind][0]
    risks = prioritize([r for r in d["risks"] if r["status"] != "Closed"], d["appetite"])
    if kind == "exec_dashboard":
        body = (f"<h2>Organisational health</h2>{_tiles(d)}<h2>Key messages</h2><ul>"
                + "".join(f"<li>{esc(x)}</li>" for x in _insights(d)) + "</ul>"
                f"<h2>Risk profile</h2>{_heatmap(d, False)}{_heatmap(d, True)}"
                f"<h2>Top five risks</h2>{_risk_table(d, risks[:5])}<h2>Key risk indicators</h2>{_kri_table(d)}")
    elif kind == "top_risks":
        body = f"<h2>Top ten risks by priority</h2>{_risk_table(d, risks[:10])}"
    elif kind == "heatmap":
        moved = [r for r in d["risks"] if r["inh_score"] != r["res_score"]]
        body = (f"<h2>Heat maps</h2>{_heatmap(d, False)}{_heatmap(d, True)}<h2>Control effect</h2>"
                f"<p>{len(moved)} of {len(d['risks'])} risks have a lower residual than inherent rating.</p>")
    elif kind == "kri_trends":
        body = f"<h2>Indicators</h2>{_kri_table(d)}"
    elif kind == "risk_committee":
        inv = d["investments"][:8]
        inv_rows = "".join(f"<tr><td>{esc(i['title'])}</td><td>{esc(i['risk_id'])}</td><td>{_money(d, i['cost'])}</td>"
                           f"<td>{_money(d, i['el_before'] - i['el_after'])}</td><td>{esc(i['status'])}</td>"
                           f"<td>{esc(i['decided_by'])}</td></tr>" for i in inv) or "<tr><td colspan=6>None this period</td></tr>"
        fnd = [f for f in d["findings"] if f.get("status") != "Closed"]
        f_rows = "".join(f"<tr><td>{esc(f['finding_id'])}</td><td>{esc(f['title'])}</td><td>{_tag(f['severity'])}</td>"
                         f"<td>{esc(f['owner'])}</td><td>Month {esc(f['due_period'])}</td><td>{esc(f['status'])}</td></tr>"
                         for f in fnd) or "<tr><td colspan=6>No open findings</td></tr>"
        events = [e for e in d["events"] if e["type"] in ("incident", "scheduled", "random")][:8]
        e_rows = "".join(f"<tr><td>Month {e['period']}</td><td>{esc(e['title'])}</td><td>{esc(e['text'])}</td></tr>"
                         for e in events) or "<tr><td colspan=3>No incidents recorded</td></tr>"
        body = (f"<h2>1. Summary for the committee</h2><ul>" + "".join(f"<li>{esc(x)}</li>" for x in _insights(d))
                + f"</ul><h2>2. Organisational health</h2>{_tiles(d)}<h2>3. Risk profile against appetite</h2>"
                f"{_heatmap(d, True)}{_risk_table(d, risks[:10])}<h2>4. Key risk indicators</h2>{_kri_table(d)}"
                f"<h2>5. Incidents and events</h2><table><tr><th>When</th><th>Event</th><th>Detail</th></tr>{e_rows}</table>"
                f"<h2>6. Treatment investments</h2><table><tr><th>Proposal</th><th>Risk</th><th>Cost</th>"
                f"<th>Annual EL reduction</th><th>Status</th><th>Decided by</th></tr>{inv_rows}</table>"
                f"<h2>7. Assurance findings</h2><table><tr><th>ID</th><th>Finding</th><th>Severity</th><th>Owner</th>"
                f"<th>Due</th><th>Status</th></tr>{f_rows}</table>"
                f"<h2>8. Risk function budget</h2><p>Remaining: {_money(d, d['budget'])}</p>")
    elif kind == "board_summary":
        decisions = [r for r in risks if r["appetite"] == "Outside tolerance"][:5]
        dec = "".join(f"<li><b>{esc(r['risk_id'])} {esc(r['title'])}</b>: residual {r['res_score']} "
                      f"({esc(r['treatment'])}). Board to confirm treatment or formally accept.</li>" for r in decisions)
        body = (f"<h2>Risk profile in one view</h2>{_heatmap(d, True)}<h2>What the board needs to know</h2><ul>"
                + "".join(f"<li>{esc(x)}</li>" for x in _insights(d)[:5]) + "</ul>"
                f"<h2>Decisions requested</h2><ul>{dec or '<li>No decisions required this period.</li>'}</ul>"
                f"<h2>Top five enterprise risks</h2>{_risk_table(d, risks[:5])}"
                f"<h2>Health indicators</h2>{_tiles(d)}")
    elif kind == "investment_proposal":
        o = options
        if not o:
            raise ValueError("Investment proposal needs the cost-benefit inputs")
        rid = o.get("risk_id")
        payback = "n/a" if o.get("payback") is None else f"{o['payback']:.1f} years"
        r = next((x for x in d["risks"] if x["risk_id"] == rid), None)
        body = (f"<h2>Proposal</h2><p><b>{esc(o.get('title', 'Risk treatment'))}</b> for "
                f"{esc(rid)} {esc(r['title'] if r else '')}</p><table>"
                f"<tr><th>Expected annual loss before</th><td>{_money(d, o['el_before'])}</td></tr>"
                f"<tr><th>Expected annual loss after</th><td>{_money(d, o['el_after'])}</td></tr>"
                f"<tr><th>Annual risk reduction</th><td>{_money(d, o['el_before'] - o['el_after'])}</td></tr>"
                f"<tr><th>Upfront cost</th><td>{_money(d, o['upfront'])}</td></tr>"
                f"<tr><th>Annual running cost</th><td>{_money(d, o['annual'])}</td></tr>"
                f"<tr><th>Horizon / discount rate</th><td>{o['years']} years / {o['rate'] * 100:.1f}%</td></tr>"
                f"<tr><th>NPV</th><td><b>{_money(d, o['npv'])}</b></td></tr>"
                f"<tr><th>ROI (undiscounted)</th><td>{o['roi'] * 100:.0f}%</td></tr>"
                f"<tr><th>Payback</th><td>{payback}</td></tr>"
                f"</table><h2>Assumptions and uncertainty</h2><p>{esc(o.get('assumptions', 'Expected loss figures are estimates. Worst-case loss can far exceed expected loss.'))}</p>"
                f"<h2>Recommendation</h2><p>{'Proceed: positive NPV.' if o['npv'] > 0 else 'Do not proceed on financial grounds alone; consider non-financial benefits (safety, compliance, reputation).'}</p>")
    elif kind == "post_incident":
        ev = options.get("event")
        if not ev:
            raise ValueError("Choose an incident to review")
        body = (f"<h2>Incident</h2><p><b>{esc(ev['title'])}</b> (Month {ev['period']})</p><p>{esc(ev['text'])}</p>"
                f"<p class='note'>{esc(ev.get('data', {}).get('judgement', ''))}</p>"
                f"<h2>Root cause</h2><p>{esc(options.get('root_cause', 'Not yet determined'))}</p>"
                f"<h2>What worked</h2><p>{esc(options.get('worked', ''))}</p>"
                f"<h2>What did not</h2><p>{esc(options.get('failed', ''))}</p>"
                f"<h2>Actions</h2><p>{esc(options.get('actions', ''))}</p>"
                f"<h2>Was this judgement or luck?</h2><p>{esc(options.get('luck', ev.get('data', {}).get('judgement', '')))}</p>")
    return _doc(title, d, body)
